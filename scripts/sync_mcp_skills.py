#!/usr/bin/env python3
"""Bundle skills/ Markdown files into the National Focus Edge Function."""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SKILLS_DIR = ROOT / 'skills'
TARGET = ROOT / 'supabase' / 'functions' / 'national-focus-mcp' / 'skills_bundle.ts'


def parse_frontmatter(text: str, path: Path) -> tuple[str, str]:
    match = re.match(r'^---\r?\n(.*?)\r?\n---\r?\n', text, re.DOTALL)
    if not match:
        raise ValueError(f'{path}: missing YAML frontmatter')
    name = ''
    description = ''
    for line in match.group(1).splitlines():
        if line.startswith('name:'):
            name = line.split(':', 1)[1].strip().strip('"\'')
        elif line.startswith('description:'):
            description = line.split(':', 1)[1].strip().strip('"\'')
    if not name or not description:
        raise ValueError(f'{path}: frontmatter must define name and description')
    return name, description


def collect_skills() -> list[dict[str, object]]:
    if not SKILLS_DIR.is_dir():
        return []
    bundled: list[dict[str, object]] = []
    for entry in sorted(SKILLS_DIR.iterdir(), key=lambda item: item.name):
        if not entry.is_dir():
            continue
        skill_file = entry / 'SKILL.md'
        if not skill_file.is_file():
            continue
        skill_text = skill_file.read_text(encoding='utf-8').replace('\r\n', '\n')
        name, description = parse_frontmatter(skill_text, skill_file)
        references: list[dict[str, str]] = []
        refs_dir = entry / 'references'
        if refs_dir.is_dir():
            for ref_file in sorted(refs_dir.glob('*.md'), key=lambda item: item.name):
                references.append({
                    'path': f'references/{ref_file.name}',
                    'uri': f'pacta://skills/{entry.name}/references/{ref_file.name}',
                    'content': ref_file.read_text(encoding='utf-8').replace('\r\n', '\n'),
                })
        bundled.append({
            'slug': entry.name,
            'name': name,
            'description': description,
            'uri': f'pacta://skills/{entry.name}/SKILL.md',
            'skill_md': skill_text,
            'references': references,
        })
    return bundled


def render_ts(skills: list[dict[str, object]]) -> str:
    payload = json.dumps(skills, ensure_ascii=False, indent=2)
    return (
        '// Generated by scripts/sync_mcp_skills.py. Do not edit manually.\n'
        'export interface BundledSkillReference {\n'
        '  readonly path: string;\n'
        '  readonly uri: string;\n'
        '  readonly content: string;\n'
        '}\n\n'
        'export interface BundledSkill {\n'
        '  readonly slug: string;\n'
        '  readonly name: string;\n'
        '  readonly description: string;\n'
        '  readonly uri: string;\n'
        '  readonly skill_md: string;\n'
        '  readonly references: readonly BundledSkillReference[];\n'
        '}\n\n'
        f'export const BUNDLED_SKILLS: readonly BundledSkill[] = {payload};\n'
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        '--check',
        action='store_true',
        help='verify skills_bundle.ts is up to date without writing',
    )
    args = parser.parse_args(argv)
    rendered = render_ts(collect_skills())
    if args.check:
        if not TARGET.is_file():
            print(f'missing generated bundle: {TARGET}', file=sys.stderr)
            return 1
        current = TARGET.read_text(encoding='utf-8').replace('\r\n', '\n')
        if current != rendered:
            print(
                f'{TARGET} is out of date; run: python scripts/sync_mcp_skills.py',
                file=sys.stderr,
            )
            return 1
        print(f'skills bundle: OK ({TARGET.relative_to(ROOT)})')
        return 0
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(rendered, encoding='utf-8', newline='\n')
    print(f'generated {TARGET.relative_to(ROOT)}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
