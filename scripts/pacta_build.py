def handle_build(arguments, context: Context) -> int:
    mode = _mode_from(arguments)
    defines, file_values, env_file = _resolve_defines(arguments, context)
    _require_defines(defines, env_file=env_file)
    _report_ignored(context, file_values)
    _print_header(context, defines, env_file)

    require_release_signing = bool(getattr(arguments, 'require_release_signing', False))
    if require_release_signing and arguments.target == 'windows':
        print(
            '[pacta] 提示：--require-release-signing 只影响 Android APK/AAB 构建，'
            'Windows 构建已忽略该要求。',
            file=context.out,
        )

    split_per_abi = bool(getattr(arguments, 'split_per_abi', False))
    steps = prepare_steps(
        context.repo,
        skip_fonts=bool(getattr(arguments, 'skip_fonts', False)),
        skip_pub_get=bool(getattr(arguments, 'skip_pub_get', False)),
    )
    planned = flutter_build_commands(
        arguments.target,
        defines_path=DEFINES_PLACEHOLDER,
        mode=mode,
        split_per_abi=split_per_abi,
    )
    if arguments.dry_run:
        _print_plan(
            context,
            action='build --target {} --{}'.format(arguments.target, mode),
            defines=defines,
            file_values=file_values,
            env_file=env_file,
            steps=steps,
            commands=planned,
            require_release_signing=require_release_signing,
        )
        if arguments.target in ('windows', 'all') and not getattr(
            arguments, 'skip_windows_package', False
        ):
            print(
                '[dry-run] Windows 产物打包：便携包 {} 与安装程序 {}（Inno Setup {}）'.format(
                    windows_portable_zip_path(context.repo, mode),
                    windows_setup_exe_path(context.repo),
                    context.repo / DEFAULT_WINDOWS_ISS,
                ),
                file=context.out,
            )
        return EXIT_OK

    _run_steps(steps, context)
    environment = build_env(context.environ, require_release_signing=require_release_signing)
    with defines_file(defines) as path:
        commands = flutter_build_commands(
            arguments.target,
            defines_path=path,
            mode=mode,
            split_per_abi=split_per_abi,
        )
        for command in commands:
            result = context.runner.run(command, cwd=context.repo, env=environment)
            if result.returncode != 0:
                raise BuildError(
                    '构建失败（退出码 {}）：{}'.format(
                        result.returncode, format_command(command)
                    )
                )
    _package_windows_artifacts(arguments, context, mode=mode)
    return EXIT_OK


def handle_run(arguments, context: Context) -> int:
    mode = _mode_from(arguments)
    defines, file_values, env_file = _resolve_defines(arguments, context)
    _require_defines(defines, env_file=env_file)
    _report_ignored(context, file_values)
    _print_header(context, defines, env_file)

    target = (arguments.target or 'windows').strip()
    device = resolve_android_device(context) if target == 'android' else target
    steps = prepare_steps(
        context.repo,
        skip_fonts=bool(getattr(arguments, 'skip_fonts', False)),
        skip_pub_get=bool(getattr(arguments, 'skip_pub_get', False)),
    )
    planned = [
        flutter_run_command(device=device, defines_path=DEFINES_PLACEHOLDER, mode=mode)
    ]
    if arguments.dry_run:
        _print_plan(
            context,
            action='run -d {} --{}'.format(device, mode),
            defines=defines,
            file_values=file_values,
            env_file=env_file,
            steps=steps,
            commands=planned,
            require_release_signing=False,
        )
        return EXIT_OK

    _run_steps(steps, context)
    with defines_file(defines) as path:
        command = flutter_run_command(device=device, defines_path=path, mode=mode)
        result = context.runner.run(
            command,
            cwd=context.repo,
            env=build_env(context.environ, require_release_signing=False),
        )
        if result.returncode != 0:
            raise BuildError(
                '运行失败（退出码 {}）：{}'.format(result.returncode, format_command(command))
            )
    return EXIT_OK


def _mode_from(arguments) -> str:
    for mode in BUILD_MODES:
        if getattr(arguments, 'mode_' + mode, False):
            return mode
    return getattr(arguments, 'mode', 'debug' if arguments.command == 'run' else 'release')


