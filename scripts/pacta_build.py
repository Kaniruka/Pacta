#!/usr/bin/env python3
"""One-command Flutter build helper for Pacta.

The Flutter client may only ever receive two Supabase values:

    SUPABASE_URL
    SUPABASE_PUBLISHABLE_KEY

Every other key in `.env` (secret key, service role key, personal access token,
`TEST_*` fixtures, `ANDROID_KEYSTORE_*`) is dropped before Flutter starts. The
raw `.env` file is never handed to `--dart-define-from-file`; a temporary
JSON file that holds the two whitelisted keys is generated, passed to Flutter
and deleted in a `finally` block.

Usage (repository root):

    python scripts/pacta_build.py run --target windows
    python scripts/pacta_build.py run -d emulator-5554 --profile
    python scripts/pacta_build.py build --target apk --release
    python scripts/pacta_build.py build --target all --release --require-release-signing
    python scripts/pacta_build.py build --target windows --release --dry-run
    python scripts/pacta_build.py init-keystore

Value resolution order for the two client keys:
command line option > process environment > the `--env-file` file.

Exit codes:
    0  success
    1  a build step failed (or the keystore could not be created)
    2  a required client key is missing
"""

from __future__ import annotations

import argparse
import contextlib
import dataclasses
import json
import os
from pathlib import Path
import re
import secrets
import shutil
import string
import subprocess
import sys
import tempfile
from typing import Iterable, Iterator, Mapping, Optional, Sequence, TextIO

REPO = Path(__file__).resolve().parents[1]

EXIT_OK = 0
EXIT_FAILED = 1
EXIT_MISSING_CONFIG = 2

# The complete set of keys a client build may receive.
CLIENT_DEFINE_KEYS = ('SUPABASE_URL', 'SUPABASE_PUBLISHABLE_KEY')

DEFAULT_ENV_FILE = '.env'
DEFAULT_KEYSTORE = 'android/app/upload-keystore.jks'
DEFAULT_PROPERTIES = 'android/key.properties'
DEFAULT_ALIAS = 'pacta-upload'
DEFAULT_DNAME = 'CN=Pacta Upload, OU=Release, O=Rukani, L=Shanghai, ST=Shanghai, C=CN'
DEFAULT_VALIDITY_DAYS = 10000
DEFAULT_PASSWORD_LENGTH = 24
PASSWORD_ALPHABET = string.ascii_letters + string.digits

BUILD_TARGETS = ('windows', 'apk', 'appbundle', 'all')
BUILD_MODES = ('release', 'profile', 'debug')

DEFINES_FILE_PREFIX = '.dart-defines-'
DEFINES_PLACEHOLDER = '<TMP>/pacta-defines-XXXXXX.json'

PROPERTIES_HEADER = (
    '# Generated by scripts/pacta_build.py init-keystore.',
    '# Git-ignored: never commit this file or the keystore it points at.',
)

GRADLE_REQUIRE_SIGNING_ENV = 'ORG_GRADLE_PROJECT_requireReleaseSigning'
SIGNING_REQUIRED_ENV = 'PACTA_REQUIRE_RELEASE_SIGNING'

_KEY_PATTERN = re.compile(r'^[A-Za-z_][A-Za-z0-9_.]*$')
_ESCAPES = {'n': '\n', 'r': '\r', 't': '\t', '\\': '\\', '"': '"', "'": "'"}


class BuildError(Exception):
    """A user-facing failure carrying its process exit code."""

    def __init__(self, message: str, exit_code: int = EXIT_FAILED) -> None:
        super().__init__(message)
        self.exit_code = exit_code


@dataclasses.dataclass(frozen=True)
class CommandResult:
    """Outcome of one external command."""

    returncode: int
    stdout: str = ''
    stderr: str = ''


class Runner:
    """Executes external commands; tests substitute a recording fake."""

    def run(
        self,
        command: Sequence[str],
        *,
        cwd: Optional[Path] = None,
        env: Optional[Mapping[str, str]] = None,
        capture: bool = False,
        echo: bool = True,
    ) -> CommandResult:
        raise NotImplementedError


class SubprocessRunner(Runner):
    """Real runner: echoes the command, then executes it."""

    def __init__(self, stream: Optional[TextIO] = None) -> None:
        self._stream = stream if stream is not None else sys.stdout

    def run(
        self,
        command: Sequence[str],
        *,
        cwd: Optional[Path] = None,
        env: Optional[Mapping[str, str]] = None,
        capture: bool = False,
        echo: bool = True,
    ) -> CommandResult:
        if echo:
            print('$ ' + format_command(command), file=self._stream, flush=True)
        completed = subprocess.run(
            list(command),
            cwd=str(cwd) if cwd is not None else None,
            env=None if env is None else dict(env),
            text=True,
            stdout=subprocess.PIPE if capture else None,
            stderr=subprocess.PIPE if capture else None,
            check=False,
        )
        return CommandResult(
            returncode=completed.returncode,
            stdout=completed.stdout or '',
            stderr=completed.stderr or '',
        )


@dataclasses.dataclass(frozen=True)
class Context:
    """Everything a subcommand needs, injected so tests stay offline."""

    repo: Path
    runner: Runner
    environ: Mapping[str, str]
    out: TextIO
    err: TextIO
    input_fn: object = input


