def collect_client_defines(
    *,
    cli: Optional[Mapping[str, Optional[str]]] = None,
    environ: Optional[Mapping[str, str]] = None,
    file_values: Optional[Mapping[str, str]] = None,
) -> dict:
    """Resolve the two client keys: CLI, then environment, then `.env` file."""
    cli = cli or {}
    environ = os.environ if environ is None else environ
    file_values = file_values or {}
    resolved: dict = {}
    for key in CLIENT_DEFINE_KEYS:
        for candidate in (cli.get(key), environ.get(key), file_values.get(key)):
            value = (candidate or '').strip()
            if value:
                resolved[key] = value
                break
    return resolved


def ignored_keys(file_values: Mapping[str, str]) -> list:
    """Keys present in `.env` that are deliberately never injected."""
    return sorted(key for key in file_values if key not in CLIENT_DEFINE_KEYS)


def defines_payload(defines: Mapping[str, str]) -> dict:
    """The exact JSON object handed to Flutter: whitelisted keys only."""
    return {key: defines[key] for key in CLIENT_DEFINE_KEYS if defines.get(key)}


def mask(value: str) -> str:
    """Redacted form used by `--dry-run`; the length is not sensitive."""
    return '*' * 8 + ' (len={})'.format(len(value))


@contextlib.contextmanager
def defines_file(defines: Mapping[str, str]) -> Iterator[Path]:
    """Write a whitelisted defines JSON file and always delete it again."""
    handle, name = tempfile.mkstemp(prefix=DEFINES_FILE_PREFIX, suffix='.json')
    path = Path(name)
    try:
        with os.fdopen(handle, 'w', encoding='utf-8') as stream:
            json.dump(defines_payload(defines), stream)
        yield path
    finally:
        try:
            path.unlink()
        except FileNotFoundError:
            pass


