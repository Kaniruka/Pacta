def tool_command(tool: str, *arguments: str) -> list:
    """Build an argv for `tool`, working around Windows `.bat` shims."""
    resolved = shutil.which(tool)
    if resolved and sys.platform == 'win32' and resolved.lower().endswith(('.bat', '.cmd')):
        interpreter = os.environ.get('COMSPEC') or 'cmd.exe'
        return [interpreter, '/c', resolved, *arguments]
    return [resolved or tool, *arguments]


def format_command(command: Iterable[str]) -> str:
    """Single-line, copy-pasteable rendering used by logs and `--dry-run`."""
    return subprocess.list2cmdline(list(command))


def prepare_steps(
    repo: Path,
    *,
    skip_fonts: bool = False,
    skip_pub_get: bool = False,
    python: Optional[str] = None,
) -> list:
    """Steps that must finish before Flutter invokes the platform build."""
    interpreter = python or sys.executable
    steps: list = []
    if not skip_fonts:
        steps.append([interpreter, str(repo / 'scripts' / 'fetch_misans.py')])
    if not skip_pub_get:
        steps.append(tool_command('flutter', 'pub', 'get'))
    return steps


def flutter_build_commands(
    target: str,
    *,
    defines_path: object,
    mode: str = 'release',
    split_per_abi: bool = False,
) -> list:
    """One `flutter build` command per requested target, in a stable order."""
    targets = BUILD_TARGETS[:-1] if target == 'all' else (target,)
    commands: list = []
    for name in targets:
        arguments = ['build', name, '--{}'.format(mode)]
        if name == 'apk' and split_per_abi:
            arguments.append('--split-per-abi')
        arguments.append('--dart-define-from-file={}'.format(defines_path))
        commands.append(tool_command('flutter', *arguments))
    return commands


def flutter_run_command(*, device: str, defines_path: object, mode: str = 'debug') -> list:
    return tool_command(
        'flutter',
        'run',
        '-d',
        device,
        '--{}'.format(mode),
        '--dart-define-from-file={}'.format(defines_path),
    )


def build_env(environ: Mapping[str, str], *, require_release_signing: bool) -> dict:
    """Process environment for a build; adds the Gradle signing requirement."""
    environment = dict(environ)
    if require_release_signing:
        environment[GRADLE_REQUIRE_SIGNING_ENV] = 'true'
        environment[SIGNING_REQUIRED_ENV] = 'true'
    return environment


def resolve_android_device(context: Context) -> str:
    """First supported Android device/emulator reported by the Flutter SDK."""
    command = tool_command('flutter', 'devices', '--machine')
    result = context.runner.run(command, cwd=context.repo, capture=True, echo=False)
    if result.returncode != 0:
        raise BuildError(
            '无法列出 Flutter 设备：{}'.format(result.stderr.strip() or '未知错误')
        )
    try:
        devices = json.loads(result.stdout or '[]')
    except json.JSONDecodeError as error:
        raise BuildError('`flutter devices --machine` 输出无法解析：{}'.format(error)) from error
    for device in devices:
        platform = str(device.get('targetPlatform', '')).lower()
        identifier = str(device.get('id') or '').strip()
        if 'android' in platform and identifier and device.get('isSupported', True):
            return identifier
    raise BuildError(
        '没有可用的 Android 设备或模拟器。先启动模拟器/连接设备，'
        '或用 `--target <device-id>` 指定（设备 ID 见 `flutter devices`）。'
    )


