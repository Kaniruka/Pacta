def _scan_quoted(text: str) -> Optional[str]:
    """Return the value of a fully quoted string, or None when unterminated."""
    quote = text[0]
    characters: list[str] = []
    escaped = False
    for index, character in enumerate(text[1:], start=1):
        if quote == '"' and escaped:
            characters.append(_ESCAPES.get(character, character))
            escaped = False
            continue
        if quote == '"' and character == '\\':
            escaped = True
            continue
        if character == quote:
            return ''.join(characters)
        characters.append(character)
    return None


def parse_value(raw: str) -> str:
    """Parse one dotenv value: quoted, escaped, or bare with inline comment."""
    text = raw.strip()
    if text[:1] in ('"', "'"):
        value = _scan_quoted(text)
        if value is not None:
            return value
    comment = text.find(' #')
    if comment >= 0:
        text = text[:comment]
    return text.strip()


def parse_dotenv(text: str) -> dict:
    """Parse dotenv text: BOM, CRLF, comments, `export`, quotes, escapes."""
    if text.startswith('\ufeff'):
        text = text[1:]
    values: dict = {}
    for raw_line in text.splitlines():
        line = raw_line.strip()
        if not line or line.startswith('#'):
            continue
        if line.startswith('export '):
            line = line[len('export '):].lstrip()
        key, separator, remainder = line.partition('=')
        if not separator:
            continue
        key = key.strip()
        if not key or not _KEY_PATTERN.match(key):
            continue
        values[key] = parse_value(remainder)
    return values


def read_env_file(path: Path) -> dict:
    """Read a dotenv file; a missing file yields no values instead of failing."""
    if not path.is_file():
        return {}
    try:
        text = path.read_text(encoding='utf-8-sig')
    except OSError as error:
        raise BuildError('无法读取环境文件 {}：{}'.format(path, error)) from error
    return parse_dotenv(text)


