def _resolve_defines(arguments, context: Context):
    env_file = Path(getattr(arguments, 'env_file', DEFAULT_ENV_FILE) or DEFAULT_ENV_FILE)
    if not env_file.is_absolute():
        env_file = context.repo / env_file
    file_values = read_env_file(env_file)
    defines = collect_client_defines(
        cli={
            'SUPABASE_URL': getattr(arguments, 'supabase_url', None),
            'SUPABASE_PUBLISHABLE_KEY': getattr(arguments, 'supabase_publishable_key', None),
        },
        environ=context.environ,
        file_values=file_values,
    )
    return defines, file_values, env_file


def _require_defines(defines: Mapping[str, str], *, env_file: Path) -> None:
    missing = [key for key in CLIENT_DEFINE_KEYS if key not in defines]
    if not missing:
        return
    raise BuildError(
        '缺少客户端必需配置：{}。\n'
        '  取值顺序：命令行 --supabase-url/--supabase-publishable-key > 进程环境变量 > {}。\n'
        '  修复：`Copy-Item .env.example .env` 后填写这两个键，或设置同名进程环境变量。\n'
        '  说明：只有 {} 会被注入 Flutter，secret/service_role/access token 一律忽略。'.format(
            ', '.join(missing), env_file, ' / '.join(CLIENT_DEFINE_KEYS)
        ),
        EXIT_MISSING_CONFIG,
    )


def _report_ignored(context: Context, file_values: Mapping[str, str]) -> None:
    dropped = ignored_keys(file_values)
    if dropped:
        print(
            '[pacta] 已忽略 {} 个非白名单键（不会注入、不会写入临时文件）：{}'.format(
                len(dropped), ', '.join(dropped)
            ),
            file=context.out,
        )


def _print_header(context: Context, defines: Mapping[str, str], env_file: Path) -> None:
    for key in CLIENT_DEFINE_KEYS:
        state = '已配置' if key in defines else '缺失'
        print('[pacta] {}：{}'.format(key, state), file=context.out)
    print(
        '[pacta] 配置来源：进程环境变量 / {}'.format(
            env_file if env_file.is_file() else '{}（未找到）'.format(env_file)
        ),
        file=context.out,
    )


def _print_plan(
    context: Context,
    *,
    action: str,
    defines: Mapping[str, str],
    file_values: Mapping[str, str],
    env_file: Path,
    steps: Sequence[Sequence[str]],
    commands: Sequence[Sequence[str]],
    require_release_signing: bool,
) -> None:
    print('[dry-run] 计划：{}'.format(action), file=context.out)
    print('[dry-run] 配置来源：{}'.format(env_file), file=context.out)
    for key in CLIENT_DEFINE_KEYS:
        value = defines.get(key)
        print(
            '[dry-run]   {}={}'.format(key, mask(value) if value else '<缺失>'),
            file=context.out,
        )
    dropped = ignored_keys(file_values)
    if dropped:
        print('[dry-run]   已忽略的非白名单键：{}'.format(', '.join(dropped)), file=context.out)
    print(
        '[dry-run] 白名单 JSON 写入系统临时目录，构建结束后删除；'
        '`--dart-define-from-file` 只指向该临时文件。',
        file=context.out,
    )
    print('[dry-run] 将执行的命令：', file=context.out)
    for index, command in enumerate(list(steps) + list(commands), start=1):
        print('  {}. {}'.format(index, format_command(command)), file=context.out)
    if require_release_signing:
        print(
            '[dry-run] 将设置 {}=true；缺少正式签名时 Gradle 在配置期失败。'.format(
                GRADLE_REQUIRE_SIGNING_ENV
            ),
            file=context.out,
        )


def _run_steps(steps: Sequence[Sequence[str]], context: Context) -> int:
    for step in steps:
        result = context.runner.run(step, cwd=context.repo, env=None)
        if result.returncode != 0:
            raise BuildError(
                '构建步骤失败（退出码 {}）：{}'.format(
                    result.returncode, format_command(step)
                )
            )
    return EXIT_OK


