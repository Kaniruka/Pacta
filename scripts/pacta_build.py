def find_keytool(
    *,
    environ: Optional[Mapping[str, str]] = None,
    which=None,
    platform: Optional[str] = None,
    studio_roots: Optional[Sequence[Path]] = None,
) -> Optional[Path]:
    """Locate `keytool`: PATH, then JAVA_HOME, then Android Studio's bundled JDK."""
    environ = os.environ if environ is None else environ
    platform = sys.platform if platform is None else platform
    which = shutil.which if which is None else which

    found = which('keytool')
    if found:
        return Path(found)

    java_home = (environ.get('JAVA_HOME') or '').strip()
    if java_home:
        for name in ('keytool.exe', 'keytool'):
            candidate = Path(java_home) / 'bin' / name
            if candidate.is_file():
                return candidate

    if studio_roots is None:
        roots: list = []
        if platform.startswith('win'):
            for variable, fallback in (
                ('ProgramFiles', r'C:\Program Files'),
                ('ProgramFiles(x86)', r'C:\Program Files (x86)'),
            ):
                root = Path((environ.get(variable) or fallback).strip())
                roots.append(root / 'Android' / 'Android Studio' / 'jbr' / 'bin')
            for variable in ('LOCALAPPDATA',):
                value = (environ.get(variable) or '').strip()
                if value:
                    base = Path(value)
                    roots.append(base / 'Programs' / 'Android Studio' / 'jbr' / 'bin')
                    roots.append(
                        base / 'JetBrains' / 'Toolbox' / 'apps' / 'Android Studio' / 'jbr' / 'bin'
                    )
        else:
            roots.append(
                Path('/Applications/Android Studio.app/Contents/jbr/Contents/Home/bin')
            )
            roots.append(Path.home() / 'android-studio' / 'jbr' / 'bin')
        studio_roots = roots

    for root in studio_roots:
        for name in ('keytool.exe', 'keytool'):
            candidate = Path(root) / name
            if candidate.is_file():
                return candidate
    return None


def generate_password(length: int = DEFAULT_PASSWORD_LENGTH, *, chooser=None) -> str:
    """Random alphanumeric password; avoids shell and properties quoting issues."""
    if length < 12:
        raise ValueError('password length must be at least 12')
    chooser = secrets.choice if chooser is None else chooser
    characters = [chooser(PASSWORD_ALPHABET) for _ in range(length)]
    characters[0] = chooser(string.ascii_uppercase)
    characters[1] = chooser(string.ascii_lowercase)
    characters[2] = chooser(string.digits)
    return ''.join(characters)


def keytool_command(
    keytool: Path,
    *,
    keystore: Path,
    alias: str,
    dname: str,
    store_password: str,
    key_password: str,
    storetype: str = 'PKCS12',
    validity: int = DEFAULT_VALIDITY_DAYS,
) -> list:
    return [
        str(keytool),
        '-genkeypair',
        '-noprompt',
        '-keystore',
        str(keystore),
        '-storetype',
        storetype,
        '-alias',
        alias,
        '-keyalg',
        'RSA',
        '-keysize',
        '2048',
        '-validity',
        str(validity),
        '-dname',
        dname,
        '-storepass',
        store_password,
        '-keypass',
        key_password,
    ]


def masked_command(command: Sequence[str], secrets_to_hide: Iterable[str]) -> str:
    """Command line with credential values replaced before printing."""
    text = format_command(command)
    for secret_value in secrets_to_hide:
        if secret_value:
            text = text.replace(secret_value, '<hidden>')
    return text


def properties_text(
    *,
    store_file: str,
    store_password: str,
    key_alias: str,
    key_password: str,
) -> str:
    lines = list(PROPERTIES_HEADER) + [
        'storeFile={}'.format(store_file),
        'storePassword={}'.format(store_password),
        'keyAlias={}'.format(key_alias),
        'keyPassword={}'.format(key_password),
    ]
    return '\n'.join(lines) + '\n'


def gradle_store_file_value(keystore: Path, *, app_dir: Path) -> str:
    """`storeFile` as Gradle resolves it: relative to `android/app/`."""
    try:
        relative = os.path.relpath(keystore, app_dir)
    except ValueError:
        relative = str(keystore)
    value = relative if not relative.startswith('..') else str(keystore)
    return value.replace('\\', '/')


def _resolve_repo_path(repo: Path, value: str) -> Path:
    path = Path(value)
    return path if path.is_absolute() else repo / path


def handle_init_keystore(arguments, context: Context) -> int:
    keystore = _resolve_repo_path(context.repo, arguments.keystore)
    properties = _resolve_repo_path(context.repo, arguments.properties)
    alias = arguments.alias
    existing = [path for path in (keystore, properties) if path.is_file()]
    if existing and not arguments.force:
        print(
            '[pacta] 已存在签名文件，未做任何覆盖：{}。\n'
            '  需要重新生成请显式追加 --force（旧文件会被替换）。'.format(
                '、'.join(str(path) for path in existing)
            ),
            file=context.out,
        )
        if keystore.is_file() and properties.is_file() and not getattr(arguments, 'dry_run', False):
            _try_export_github_secrets_summary(
                arguments, context, keystore=keystore, properties=properties
            )
        return EXIT_OK

    keytool = find_keytool(environ=context.environ)
    if keytool is None:
        raise BuildError(
            '未找到 keytool。请安装 JDK 17（设置 JAVA_HOME）或 Android Studio，'
            '并确保 `java -version` 可用。'
        )

    store_password = arguments.store_password or generate_password()
    key_password = arguments.key_password or store_password
    storetype = 'PKCS12' if store_password == key_password else 'JKS'
    command = keytool_command(
        keytool,
        keystore=keystore,
        alias=alias,
        dname=arguments.dname,
        store_password=store_password,
        key_password=key_password,
        storetype=storetype,
    )
    store_file = gradle_store_file_value(keystore, app_dir=context.repo / 'android' / 'app')

    if arguments.dry_run:
        print('[dry-run] keytool：{}'.format(keytool), file=context.out)
        print('[dry-run] ' + masked_command(command, (store_password, key_password)), file=context.out)
        print(
            '[dry-run] 将写入 {}（storeFile={}）与 {}。'.format(properties, store_file, keystore),
            file=context.out,
        )
        return EXIT_OK

    keystore.parent.mkdir(parents=True, exist_ok=True)
    if arguments.force:
        for path in (keystore, properties):
            with contextlib.suppress(FileNotFoundError):
                path.unlink()

    result = context.runner.run(command, cwd=context.repo, echo=False)
    if result.returncode != 0:
        raise BuildError('keytool 执行失败（退出码 {}）。'.format(result.returncode))
    if not keystore.is_file():
        raise BuildError('keytool 未生成预期的 keystore：{}。'.format(keystore))

    properties.parent.mkdir(parents=True, exist_ok=True)
    with open(properties, 'w', encoding='utf-8', newline='\n') as stream:
        stream.write(
            properties_text(
                store_file=store_file,
                store_password=store_password,
                key_alias=alias,
                key_password=key_password,
            )
        )

    print('[pacta] 已生成 Android Release 签名：', file=context.out)
    print('  keystore ：{}'.format(keystore), file=context.out)
    print('  properties：{}'.format(properties), file=context.out)
    print('  alias     ：{}（密码已写入上方 properties，不在此输出）'.format(alias), file=context.out)
    _report_ignore_status(context, (keystore, properties))
    _try_export_github_secrets_summary(arguments, context, keystore=keystore, properties=properties)
    return EXIT_OK


def _try_export_github_secrets_summary(
    arguments,
    context: Context,
    *,
    keystore: Path,
    properties: Path,
) -> None:
    """Write `build/github-actions-secrets.txt` after `init-keystore` when possible."""
    try:
        secrets_map = collect_github_release_secrets(
            arguments,
            context,
            keystore=keystore,
            properties=properties,
            require_supabase=False,
        )
        output_path = write_github_secrets_file(
            context.repo,
            secrets_map=secrets_map,
            keystore=keystore,
            properties=properties,
        )
        print(
            '[pacta] 已同步生成 GitHub Actions Secrets 填写清单（含 {}）：\n'
            '  {}\n'
            '  （可直接打开该文件复制，或执行 `python scripts/pacta_build.py github-secrets --apply` 一键写入 GitHub）'.format(
                ', '.join(GITHUB_RELEASE_SECRET_KEYS), output_path
            ),
            file=context.out,
        )
    except BuildError:
        print(
            '后续可执行 `python scripts/pacta_build.py github-secrets` 一键生成 GitHub Secrets 填写清单。',
            file=context.out,
        )


def collect_github_release_secrets(
    arguments,
    context: Context,
    *,
    keystore: Path,
    properties: Path,
    require_supabase: bool = True,
) -> dict:
    """Gather all 6 GitHub Actions Release secrets from `.env` + `key.properties` + keystore."""
    defines, _, env_file = _resolve_defines(arguments, context)
    if require_supabase:
        _require_defines(defines, env_file=env_file)

    if not properties.is_file():
        raise BuildError(
            '未找到签名属性文件 {}。请先运行 `python scripts/pacta_build.py init-keystore`。'.format(
                properties
            )
        )
    if not keystore.is_file():
        raise BuildError(
            '未找到签名密钥库 {}。请先运行 `python scripts/pacta_build.py init-keystore`。'.format(
                keystore
            )
        )

    prop_values = parse_dotenv(properties.read_text(encoding='utf-8-sig'))
    store_password = (prop_values.get('storePassword') or '').strip()
    key_alias = (prop_values.get('keyAlias') or '').strip()
    key_password = (prop_values.get('keyPassword') or store_password).strip()
    if not store_password or not key_alias or not key_password:
        raise BuildError(
            '{} 缺少 storePassword / keyAlias / keyPassword 字段。'.format(properties)
        )

    keystore_b64 = base64.b64encode(keystore.read_bytes()).decode('ascii')
    return {
        'SUPABASE_URL': defines.get('SUPABASE_URL', '<请先在 .env 填写 SUPABASE_URL>'),
        'SUPABASE_PUBLISHABLE_KEY': defines.get(
            'SUPABASE_PUBLISHABLE_KEY', '<请先在 .env 填写 SUPABASE_PUBLISHABLE_KEY>'
        ),
        'ANDROID_KEYSTORE_BASE64': keystore_b64,
        'ANDROID_KEYSTORE_PASSWORD': store_password,
        'ANDROID_KEY_ALIAS': key_alias,
        'ANDROID_KEY_PASSWORD': key_password,
    }


def write_github_secrets_file(
    repo: Path,
    *,
    secrets_map: Mapping[str, str],
    keystore: Path,
    properties: Path,
    output: Optional[Path] = None,
) -> Path:
    target = _resolve_repo_path(repo, str(output or DEFAULT_GITHUB_SECRETS_FILE))
    target.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        '# Pacta GitHub Actions Release Secrets 一键填写清单',
        '# 生成工具：python scripts/pacta_build.py github-secrets',
        '# 注意：本文件位于 git 忽略目录，包含正式签名凭据，请勿提交或外传！',
        '#',
        '# 本机签名文件位置：',
        '#   密钥库 (keystore)  : {}'.format(keystore),
        '#   属性文件 (含密码)   : {}'.format(properties),
        '#',
        '# 在 GitHub 仓库 Settings -> Secrets and variables -> Actions 依次新建以下 6 个 Repository secrets：',
        '# （或者直接运行 `python scripts/pacta_build.py github-secrets --apply` 通过 gh CLI 一键写入 GitHub）',
        '',
    ]
    for key in GITHUB_RELEASE_SECRET_KEYS:
        lines.append('{}={}'.format(key, secrets_map.get(key, '')))
    target.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    return target


def handle_github_secrets(arguments, context: Context) -> int:
    keystore = _resolve_repo_path(
        context.repo, getattr(arguments, 'keystore', DEFAULT_KEYSTORE)
    )
    properties = _resolve_repo_path(
        context.repo, getattr(arguments, 'properties', DEFAULT_PROPERTIES)
    )
    output_arg = getattr(arguments, 'output', DEFAULT_GITHUB_SECRETS_FILE)
    output_path = _resolve_repo_path(context.repo, output_arg)
    apply_to_gh = bool(getattr(arguments, 'apply', False))

    if not keystore.is_file() or not properties.is_file():
        print(
            '[pacta] 尚未检测到本机 Android Release 签名文件，正在自动生成...',
            file=context.out,
        )
        init_args = _shared_namespace(
            arguments,
            command='init-keystore',
            keystore=str(keystore),
            properties=str(properties),
            alias=DEFAULT_ALIAS,
            dname=DEFAULT_DNAME,
            store_password=None,
            key_password=None,
            force=True,
        )
        rc = handle_init_keystore(init_args, context)
        if rc != EXIT_OK:
            return rc

    if getattr(arguments, 'dry_run', False):
        print(
            '[dry-run] 将从 .env、{} 与 {} 汇总 6 个 GitHub Secrets 并写入 {}。'.format(
                properties, keystore, output_path
            ),
            file=context.out,
        )
        if apply_to_gh:
            print(
                '[dry-run] 将调用 `gh secret set <NAME>` 同步：{}'.format(
                    ', '.join(GITHUB_RELEASE_SECRET_KEYS)
                ),
                file=context.out,
            )
        return EXIT_OK

    secrets_map = collect_github_release_secrets(
        arguments,
        context,
        keystore=keystore,
        properties=properties,
        require_supabase=apply_to_gh,
    )
    written = write_github_secrets_file(
        context.repo,
        secrets_map=secrets_map,
        keystore=keystore,
        properties=properties,
        output=output_path,
    )
    print('[pacta] 已生成 GitHub Actions Release Secrets 清单：', file=context.out)
    print('  清单文件（打开即可复制全部 6 项）：{}'.format(written), file=context.out)
    print('  签名密钥库位置                  ：{}'.format(keystore), file=context.out)
    print('  签名属性文件（含 store/key 密码）：{}'.format(properties), file=context.out)
    for key in GITHUB_RELEASE_SECRET_KEYS:
        value = secrets_map.get(key, '')
        state = (
            mask(value)
            if value and not value.startswith('<')
            else '<缺失：请先在 .env 配置>'
        )
        print('  - {:26s} = {}'.format(key, state), file=context.out)

    if apply_to_gh:
        for key in GITHUB_RELEASE_SECRET_KEYS:
            command = tool_command('gh', 'secret', 'set', key, '--body', secrets_map[key])
            result = context.runner.run(command, cwd=context.repo, echo=False)
            if result.returncode != 0:
                raise BuildError(
                    '`gh secret set {}` 失败（退出码 {}）。请确认已执行 `gh auth login`。'.format(
                        key, result.returncode
                    )
                )
            print('[pacta] 已推送 GitHub Secret：{}'.format(key), file=context.out)
    return EXIT_OK


def _report_ignore_status(context: Context, paths: Sequence[Path]) -> None:
    """Confirm Git ignores the generated secrets; advisory only."""
    command = ['git', '-C', str(context.repo), 'check-ignore', '-v', '--']
    command.extend(str(path) for path in paths)
    try:
        result = context.runner.run(command, capture=True, echo=False)
    except OSError:
        return
    if result.returncode == 0:
        print('[pacta] git 已忽略上述两个文件（check-ignore 通过）。', file=context.out)
    else:
        print(
            '[pacta] 警告：Git 未忽略上述文件，提交前请检查 .gitignore。',
            file=context.err,
        )


