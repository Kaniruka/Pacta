def find_keytool(
    *,
    environ: Optional[Mapping[str, str]] = None,
    which=None,
    platform: Optional[str] = None,
    studio_roots: Optional[Sequence[Path]] = None,
) -> Optional[Path]:
    """Locate `keytool`: PATH, then JAVA_HOME, then Android Studio's bundled JDK."""
    environ = os.environ if environ is None else environ
    platform = sys.platform if platform is None else platform
    which = shutil.which if which is None else which

    found = which('keytool')
    if found:
        return Path(found)

    java_home = (environ.get('JAVA_HOME') or '').strip()
    if java_home:
        for name in ('keytool.exe', 'keytool'):
            candidate = Path(java_home) / 'bin' / name
            if candidate.is_file():
                return candidate

    if studio_roots is None:
        roots: list = []
        if platform.startswith('win'):
            for variable, fallback in (
                ('ProgramFiles', r'C:\Program Files'),
                ('ProgramFiles(x86)', r'C:\Program Files (x86)'),
            ):
                root = Path((environ.get(variable) or fallback).strip())
                roots.append(root / 'Android' / 'Android Studio' / 'jbr' / 'bin')
            for variable in ('LOCALAPPDATA',):
                value = (environ.get(variable) or '').strip()
                if value:
                    base = Path(value)
                    roots.append(base / 'Programs' / 'Android Studio' / 'jbr' / 'bin')
                    roots.append(
                        base / 'JetBrains' / 'Toolbox' / 'apps' / 'Android Studio' / 'jbr' / 'bin'
                    )
        else:
            roots.append(
                Path('/Applications/Android Studio.app/Contents/jbr/Contents/Home/bin')
            )
            roots.append(Path.home() / 'android-studio' / 'jbr' / 'bin')
        studio_roots = roots

    for root in studio_roots:
        for name in ('keytool.exe', 'keytool'):
            candidate = Path(root) / name
            if candidate.is_file():
                return candidate
    return None


def generate_password(length: int = DEFAULT_PASSWORD_LENGTH, *, chooser=None) -> str:
    """Random alphanumeric password; avoids shell and properties quoting issues."""
    if length < 12:
        raise ValueError('password length must be at least 12')
    chooser = secrets.choice if chooser is None else chooser
    characters = [chooser(PASSWORD_ALPHABET) for _ in range(length)]
    characters[0] = chooser(string.ascii_uppercase)
    characters[1] = chooser(string.ascii_lowercase)
    characters[2] = chooser(string.digits)
    return ''.join(characters)


def keytool_command(
    keytool: Path,
    *,
    keystore: Path,
    alias: str,
    dname: str,
    store_password: str,
    key_password: str,
    storetype: str = 'PKCS12',
    validity: int = DEFAULT_VALIDITY_DAYS,
) -> list:
    return [
        str(keytool),
        '-genkeypair',
        '-noprompt',
        '-keystore',
        str(keystore),
        '-storetype',
        storetype,
        '-alias',
        alias,
        '-keyalg',
        'RSA',
        '-keysize',
        '2048',
        '-validity',
        str(validity),
        '-dname',
        dname,
        '-storepass',
        store_password,
        '-keypass',
        key_password,
    ]


def masked_command(command: Sequence[str], secrets_to_hide: Iterable[str]) -> str:
    """Command line with credential values replaced before printing."""
    text = format_command(command)
    for secret_value in secrets_to_hide:
        if secret_value:
            text = text.replace(secret_value, '<hidden>')
    return text


def properties_text(
    *,
    store_file: str,
    store_password: str,
    key_alias: str,
    key_password: str,
) -> str:
    lines = list(PROPERTIES_HEADER) + [
        'storeFile={}'.format(store_file),
        'storePassword={}'.format(store_password),
        'keyAlias={}'.format(key_alias),
        'keyPassword={}'.format(key_password),
    ]
    return '\n'.join(lines) + '\n'


def gradle_store_file_value(keystore: Path, *, app_dir: Path) -> str:
    """`storeFile` as Gradle resolves it: relative to `android/app/`."""
    try:
        relative = os.path.relpath(keystore, app_dir)
    except ValueError:
        relative = str(keystore)
    value = relative if not relative.startswith('..') else str(keystore)
    return value.replace('\\', '/')


def _resolve_repo_path(repo: Path, value: str) -> Path:
    path = Path(value)
    return path if path.is_absolute() else repo / path


def handle_init_keystore(arguments, context: Context) -> int:
    keystore = _resolve_repo_path(context.repo, arguments.keystore)
    properties = _resolve_repo_path(context.repo, arguments.properties)
    alias = arguments.alias
    existing = [path for path in (keystore, properties) if path.is_file()]
    if existing and not arguments.force:
        print(
            '[pacta] 已存在签名文件，未做任何覆盖：{}。\n'
            '  需要重新生成请显式追加 --force（旧文件会被替换）。'.format(
                '、'.join(str(path) for path in existing)
            ),
            file=context.out,
        )
        return EXIT_OK

    keytool = find_keytool(environ=context.environ)
    if keytool is None:
        raise BuildError(
            '未找到 keytool。请安装 JDK 17（设置 JAVA_HOME）或 Android Studio，'
            '并确保 `java -version` 可用。'
        )

    store_password = arguments.store_password or generate_password()
    key_password = arguments.key_password or store_password
    storetype = 'PKCS12' if store_password == key_password else 'JKS'
    command = keytool_command(
        keytool,
        keystore=keystore,
        alias=alias,
        dname=arguments.dname,
        store_password=store_password,
        key_password=key_password,
        storetype=storetype,
    )
    store_file = gradle_store_file_value(keystore, app_dir=context.repo / 'android' / 'app')

    if arguments.dry_run:
        print('[dry-run] keytool：{}'.format(keytool), file=context.out)
        print('[dry-run] ' + masked_command(command, (store_password, key_password)), file=context.out)
        print(
            '[dry-run] 将写入 {}（storeFile={}）与 {}。'.format(properties, store_file, keystore),
            file=context.out,
        )
        return EXIT_OK

    keystore.parent.mkdir(parents=True, exist_ok=True)
    if arguments.force:
        for path in (keystore, properties):
            with contextlib.suppress(FileNotFoundError):
                path.unlink()

    result = context.runner.run(command, cwd=context.repo, echo=False)
    if result.returncode != 0:
        raise BuildError('keytool 执行失败（退出码 {}）。'.format(result.returncode))
    if not keystore.is_file():
        raise BuildError('keytool 未生成预期的 keystore：{}。'.format(keystore))

    properties.parent.mkdir(parents=True, exist_ok=True)
    with open(properties, 'w', encoding='utf-8', newline='\n') as stream:
        stream.write(
            properties_text(
                store_file=store_file,
                store_password=store_password,
                key_alias=alias,
                key_password=key_password,
            )
        )

    print('[pacta] 已生成 Android Release 签名：', file=context.out)
    print('  keystore ：{}'.format(keystore), file=context.out)
    print('  properties：{}'.format(properties), file=context.out)
    print('  alias     ：{}（密码已写入上方 properties，不在此输出）'.format(alias), file=context.out)
    _report_ignore_status(context, (keystore, properties))
    print(
        '后续在 GitHub 仓库 Settings -> Secrets and variables -> Actions 配置：\n'
        '  SUPABASE_URL\n'
        '  SUPABASE_PUBLISHABLE_KEY\n'
        '  ANDROID_KEYSTORE_BASE64\n'
        '  ANDROID_KEYSTORE_PASSWORD\n'
        '  ANDROID_KEY_ALIAS\n'
        '  ANDROID_KEY_PASSWORD\n'
        'PowerShell 导出口令库（生成 ANDROID_KEYSTORE_BASE64 的值）：\n'
        '  [Convert]::ToBase64String([IO.File]::ReadAllBytes("{}"))'.format(
            str(keystore).replace('\\', '/')
        ),
        file=context.out,
    )
    return EXIT_OK


def _report_ignore_status(context: Context, paths: Sequence[Path]) -> None:
    """Confirm Git ignores the generated secrets; advisory only."""
    command = ['git', '-C', str(context.repo), 'check-ignore', '-v', '--']
    command.extend(str(path) for path in paths)
    try:
        result = context.runner.run(command, capture=True, echo=False)
    except OSError:
        return
    if result.returncode == 0:
        print('[pacta] git 已忽略上述两个文件（check-ignore 通过）。', file=context.out)
    else:
        print(
            '[pacta] 警告：Git 未忽略上述文件，提交前请检查 .gitignore。',
            file=context.err,
        )


