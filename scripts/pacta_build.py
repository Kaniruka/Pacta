def _add_shared_arguments(parser, *, defaults: bool) -> None:
    def default(value):
        return value if defaults else argparse.SUPPRESS

    parser.add_argument(
        '--env-file',
        default=default(DEFAULT_ENV_FILE),
        metavar='PATH',
        help='dotenv file to read (default: %s)' % DEFAULT_ENV_FILE,
    )
    parser.add_argument('--supabase-url', default=default(None), help='override SUPABASE_URL')
    parser.add_argument(
        '--supabase-publishable-key',
        default=default(None),
        help='override SUPABASE_PUBLISHABLE_KEY',
    )
    parser.add_argument('--dry-run', action='store_true', default=default(False), help='print the plan and exit')
    parser.add_argument('--skip-fonts', action='store_true', default=default(False), help='skip scripts/fetch_misans.py')
    parser.add_argument('--skip-pub-get', action='store_true', default=default(False), help='skip `flutter pub get`')


def _shared_namespace(arguments, **extra) -> argparse.Namespace:
    values = {
        'env_file': getattr(arguments, 'env_file', DEFAULT_ENV_FILE),
        'supabase_url': getattr(arguments, 'supabase_url', None),
        'supabase_publishable_key': getattr(arguments, 'supabase_publishable_key', None),
        'dry_run': bool(getattr(arguments, 'dry_run', False)),
        'skip_fonts': bool(getattr(arguments, 'skip_fonts', False)),
        'skip_pub_get': bool(getattr(arguments, 'skip_pub_get', False)),
    }
    values.update(extra)
    return argparse.Namespace(**values)


def handle_interactive(arguments, context: Context) -> int:
    defines, file_values, env_file = _resolve_defines(arguments, context)
    keystore = _resolve_repo_path(context.repo, DEFAULT_KEYSTORE)
    properties = _resolve_repo_path(context.repo, DEFAULT_PROPERTIES)
    signing_ready = keystore.is_file() and properties.is_file()

    print('=== Pacta 交互式构建与运行 ===', file=context.out)
    _report_ignored(context, file_values)
    _print_header(context, defines, env_file)
    print(
        '[pacta] Android Release 签名：{}'.format(
            '已就绪（{}）'.format(properties)
            if signing_ready
            else '未生成（可选择 7 一键生成）'
        ),
        file=context.out,
    )
    print(
        '\n请选择操作：\n'
        '  1) 运行 Windows 桌面版 (Debug)\n'
        '  2) 运行 Android 设备/模拟器 (Debug)\n'
        '  3) 构建 Windows Release\n'
        '  4) 构建 Android Release APK\n'
        '  5) 构建 Android Release AAB (Google Play)\n'
        '  6) 构建全平台 Release (Windows + APK + AAB，强制正式签名)\n'
        '  7) 生成本机 Android Release 签名 (init-keystore)\n'
        '  0) 退出',
        file=context.out,
    )

    read_input = context.input_fn if callable(context.input_fn) else input
    while True:
        try:
            choice = str(read_input('请输入编号 [1-7, 0/q 退出]: ')).strip().lower()
        except EOFError:
            print('[pacta] 已退出。', file=context.out)
            return EXIT_OK

        if choice in ('0', 'q', 'quit', 'exit'):
            print('[pacta] 已退出。', file=context.out)
            return EXIT_OK
        if choice == '1':
            return handle_run(
                _shared_namespace(arguments, command='run', target='windows', mode='debug'),
                context,
            )
        if choice == '2':
            return handle_run(
                _shared_namespace(arguments, command='run', target='android', mode='debug'),
                context,
            )
        if choice == '3':
            return handle_build(
                _shared_namespace(
                    arguments,
                    command='build',
                    target='windows',
                    mode='release',
                    split_per_abi=False,
                    require_release_signing=False,
                ),
                context,
            )
        if choice == '4':
            return handle_build(
                _shared_namespace(
                    arguments,
                    command='build',
                    target='apk',
                    mode='release',
                    split_per_abi=False,
                    require_release_signing=False,
                ),
                context,
            )
        if choice == '5':
            return handle_build(
                _shared_namespace(
                    arguments,
                    command='build',
                    target='appbundle',
                    mode='release',
                    split_per_abi=False,
                    require_release_signing=False,
                ),
                context,
            )
        if choice == '6':
            return handle_build(
                _shared_namespace(
                    arguments,
                    command='build',
                    target='all',
                    mode='release',
                    split_per_abi=False,
                    require_release_signing=True,
                ),
                context,
            )
        if choice == '7':
            return handle_init_keystore(
                _shared_namespace(
                    arguments,
                    command='init-keystore',
                    keystore=DEFAULT_KEYSTORE,
                    properties=DEFAULT_PROPERTIES,
                    alias=DEFAULT_ALIAS,
                    dname=DEFAULT_DNAME,
                    store_password=None,
                    key_password=None,
                    force=False,
                ),
                context,
            )
        print('[pacta] 无效编号 "{}"，请输入 1-7 或 0/q。'.format(choice), file=context.err)


def _add_mode_arguments(parser, *, default_mode: str) -> None:
    parser.add_argument('--mode', choices=BUILD_MODES, default=default_mode, help='build mode')
    for mode in BUILD_MODES:
        parser.add_argument(
            '--' + mode,
            dest='mode_' + mode,
            action='store_true',
            default=argparse.SUPPRESS,
            help='shorthand for --mode ' + mode,
        )


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog='pacta_build.py',
        description=(
            'Pacta 一键构建：只把 SUPABASE_URL / SUPABASE_PUBLISHABLE_KEY '
            '通过临时白名单 JSON 注入 Flutter。'
        ),
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=(
            '示例：\n'
            '  python scripts/pacta_build.py run -d windows\n'
            '  python scripts/pacta_build.py build --target apk --release\n'
            '  python scripts/pacta_build.py build --target all --require-release-signing\n'
            '  python scripts/pacta_build.py init-keystore\n'
        ),
    )
    _add_shared_arguments(parser, defaults=True)
    parser.add_argument(
        '-i',
        '--interactive',
        action='store_true',
        default=False,
        help='launch the interactive menu',
    )
    subparsers = parser.add_subparsers(dest='command', required=False)

    interactive_parser = subparsers.add_parser(
        'interactive', help='launch the interactive menu'
    )
    _add_shared_arguments(interactive_parser, defaults=False)

    run_parser = subparsers.add_parser('run', help='flutter run with whitelisted defines')
    _add_shared_arguments(run_parser, defaults=False)
    run_parser.add_argument(
        '--target',
        '-d',
        '--device',
        dest='target',
        default='windows',
        help='windows / android（自动取第一台设备）/ <device-id>',
    )
    _add_mode_arguments(run_parser, default_mode='debug')

    build_parser_ = subparsers.add_parser('build', help='flutter build with whitelisted defines')
    _add_shared_arguments(build_parser_, defaults=False)
    build_parser_.add_argument(
        '--target',
        choices=BUILD_TARGETS,
        default='apk',
        help='windows / apk / appbundle / all（默认 apk）',
    )
    _add_mode_arguments(build_parser_, default_mode='release')
    build_parser_.add_argument(
        '--split-per-abi',
        action='store_true',
        default=False,
        help='APK 按 ABI 拆分（仅对 apk 生效）',
    )
    build_parser_.add_argument(
        '--require-release-signing',
        action='store_true',
        default=False,
        help='缺失正式 Release 签名时让 Gradle 在配置期直接失败',
    )

    keystore_parser = subparsers.add_parser(
        'init-keystore', help='generate the local Android release keystore'
    )
    _add_shared_arguments(keystore_parser, defaults=False)
    keystore_parser.add_argument('--keystore', default=DEFAULT_KEYSTORE, metavar='PATH')
    keystore_parser.add_argument('--properties', default=DEFAULT_PROPERTIES, metavar='PATH')
    keystore_parser.add_argument('--alias', default=DEFAULT_ALIAS)
    keystore_parser.add_argument('--dname', default=DEFAULT_DNAME)
    keystore_parser.add_argument('--store-password', default=None)
    keystore_parser.add_argument('--key-password', default=None)
    keystore_parser.add_argument('--force', action='store_true', default=False)

    return parser


HANDLERS = {
    'build': handle_build,
    'run': handle_run,
    'init-keystore': handle_init_keystore,
    'interactive': handle_interactive,
}


def main(
    argv: Optional[Sequence[str]] = None,
    *,
    runner: Optional[Runner] = None,
    environ: Optional[Mapping[str, str]] = None,
    out: Optional[TextIO] = None,
    err: Optional[TextIO] = None,
    repo: Optional[Path] = None,
    input_fn=None,
    is_tty: Optional[bool] = None,
) -> int:
    out = sys.stdout if out is None else out
    err = sys.stderr if err is None else err
    argument_list = list(sys.argv[1:] if argv is None else argv)
    parser = build_parser()
    arguments = parser.parse_args(argument_list)
    context = Context(
        repo=Path(repo) if repo is not None else REPO,
        runner=runner if runner is not None else SubprocessRunner(out),
        environ=dict(os.environ) if environ is None else environ,
        out=out,
        err=err,
        input_fn=input if input_fn is None else input_fn,
    )
    command = arguments.command
    if command is None:
        tty_ready = (
            is_tty
            if is_tty is not None
            else (input_fn is not None or bool(getattr(sys.stdin, 'isatty', lambda: False)()))
        )
        if getattr(arguments, 'interactive', False) or (not argument_list and tty_ready):
            command = 'interactive'
        else:
            parser.print_help(file=err)
            return EXIT_MISSING_CONFIG
    try:
        return HANDLERS[command](arguments, context)
    except BuildError as error:
        print('[pacta] ' + str(error), file=err)
        return error.exit_code
    except KeyboardInterrupt:
        print('[pacta] 已中断。', file=err)
        return EXIT_FAILED


if __name__ == '__main__':
    sys.exit(main())
